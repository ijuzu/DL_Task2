import json
import random

DATASET_PATH = "dataset.jsonl"
TRAIN_PATH   = "train.jsonl"
TEST_PATH    = "test.jsonl"
SEED         = 99

# Groups of related cities (need to be put in same split)

RELATED_GROUPS = [

    frozenset(["Panemunėlis", "Panemunė", "Žemoji Panemunė"]),
    frozenset(["Radviliškis", "Nemunėlio Radviliškis"]),
    frozenset(["Šilai (Panevėžys)", "Panevėžys"]),
    frozenset(["Kėdainiai", "Akademija (Kėdainiai)"]),
    frozenset(["Kalvarija", "Žemaičių Kalvarija"]),
    frozenset(["Kretinga", "Kretingalė"]),
    frozenset(["Subačius", "Subačius (miestelis)"]),
    frozenset(["Rudamina (Lazdijai)", "Rudamina (Vilnius)"]),
    frozenset(["Pagiriai (Vilnius)", "Pagiriai"]),
    frozenset(["Joniškis", "Joniškis (Molėtai)"]),
    frozenset(["Akademija (Kaunas)", "Kaunas"]),
]


def load_jsonl(path):
    examples = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                examples.append(json.loads(line))
    return examples


def write_jsonl(data, path):
    with open(path, "w", encoding="utf-8") as f:
        for item in data:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")


def get_city_name(example):
    return example["instruction"].replace("Apibūdink: ", "").strip()


def find_group(city_name):
    for i, group in enumerate(RELATED_GROUPS):
        if city_name in group:
            return i
    return None

# Main

print("Loading dataset.jsonl...")
all_examples = load_jsonl(DATASET_PATH)
print(f"Loaded {len(all_examples)} examples")

# Remove exact duplicates by city name
seen_names = set()
deduplicated = []
duplicates_removed = []
for ex in all_examples:
    name = get_city_name(ex)
    if name not in seen_names:
        seen_names.add(name)
        deduplicated.append(ex)
    else:
        duplicates_removed.append(name)

if duplicates_removed:
    print(f"\nRemoved {len(duplicates_removed)} exact duplicate(s): {duplicates_removed}")
else:
    print("\nNo exact duplicates found.")

print(f"Examples after deduplication: {len(deduplicated)}")

# Assign each example to a group
group_dict = {}

for ex in deduplicated:
    name     = get_city_name(ex)
    group_id = find_group(name)

    if group_id is not None:
        key = f"related_{group_id}"
    else:
        key = f"solo_{name}"

    if key not in group_dict:
        group_dict[key] = []
    group_dict[key].append(ex)

# Shuffle groups and split 80/20
group_keys = list(group_dict.keys())
random.seed(SEED)
random.shuffle(group_keys)

split_idx  = int(len(group_keys) * 0.8)
train_keys = group_keys[:split_idx]
test_keys  = group_keys[split_idx:]

train_set = []
for key in train_keys:
    train_set.extend(group_dict[key])

test_set = []
for key in test_keys:
    test_set.extend(group_dict[key])

write_jsonl(train_set, TRAIN_PATH)
write_jsonl(test_set,  TEST_PATH)

train_names = sorted([get_city_name(ex) for ex in train_set])
test_names  = sorted([get_city_name(ex) for ex in test_set])

print(f"\n{'='*60}")
print(f"SPLIT COMPLETE")
print(f"{'='*60}")
print(f"  Train examples: {len(train_set)}")
print(f"  Test examples:  {len(test_set)}")

print(f"\nTEST SET CITIES (use these for demo during assessment):")
print(f"{'─'*60}")
for name in test_names:
    print(f"  {name}")

print(f"\nTRAIN SET CITIES:")
print(f"{'─'*60}")
for name in train_names:
    print(f"  {name}")

# Verify no overlap
train_name_set = set(train_names)
test_name_set  = set(test_names)
overlap        = train_name_set & test_name_set
if overlap:
    print(f"\nWARNING: {len(overlap)} city/cities still in both splits: {overlap}")
else:
    print(f"\n✓ No cities appear in both train and test.")