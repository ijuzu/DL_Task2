# extract titles from URLs

def get_all_places():
    """Convert your list of Wikipedia URLs into article titles."""
    titles = []
    for url in MY_LINKS:
        raw_title = url.split("/wiki/")[-1]
        title     = unquote(raw_title).replace("_", " ")
        titles.append(title)
    print(f"Loaded {len(titles)} places from your list.\n")
    return titles


# Fetch articles: if Wikipedia rate-limits us (returns empty or errors),
# wait and try again up to MAX_RETRIES times before giving up.

def fetch_lead_section(title):

    params = {
        "action":      "query",
        "titles":      title,
        "prop":        "extracts",
        "exintro":     True,
        "explaintext": True,
        "redirects":   True,
        "format":      "json",
    }

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            response = requests.get(
                WIKI_API, params=params, headers=HEADERS, timeout=15
            )
            response.raise_for_status()
            data  = response.json()
            pages = data["query"]["pages"]
            page  = next(iter(pages.values()))

            # pageid -1 = article doesn't exist
            if page.get("pageid") == -1:
                return None

            text = page.get("extract", "").strip()

            # Wikipedia returned a valid page but no content.
            if not text:
                raise ValueError("Empty extract returned")

            return text

        except Exception as e:
            if attempt == MAX_RETRIES:
                return None

            # Wait longer with each retry attempt
            wait = RETRY_WAIT * attempt
            print(f"\n  [rate limited, waiting {wait:.0f}s before retry {attempt}/{MAX_RETRIES}]",
                  end=" ", flush=True)
            time.sleep(wait)

    return None


# Returns cleaned text or None if the article should be skipped

def clean_and_filter(text):

    if "gali reikšti" in text:
        return None

    if len(text) < MIN_CHARS:
        return None

    if len(text) > MAX_CHARS:
        truncated   = text[:MAX_CHARS]
        last_period = truncated.rfind(".")
        if last_period == -1:
            return None
        text = truncated[:last_period + 1]

    if len(text) < MIN_CHARS:
        return None

    return text


# Dataset building

def build_dataset(places):

    dataset = []
    skipped = []

    for i, place in enumerate(places, 1):
        print(f"[{i}/{len(places)}] {place} ...", end=" ", flush=True)

        raw_text = fetch_lead_section(place)

        if raw_text is None:
            print("SKIP (not found after retries)")
            skipped.append(place)
            time.sleep(DELAY)
            continue

        clean_text = clean_and_filter(raw_text)

        if clean_text is None:
            print("SKIP (stub or disambiguation)")
            skipped.append(place)
            time.sleep(DELAY)
            continue

        dataset.append({
            "instruction": f"Apibūdink: {place}",
            "response":    clean_text,
        })
        print(f"OK ({len(clean_text)} chars)")
        time.sleep(DELAY + random.uniform(0, 0.5))

    print(f"\nCollected: {len(dataset)} | Skipped: {len(skipped)}")
    if skipped:
        print(f"Skipped: {skipped}")
    return dataset


# Train/test split

def split_dataset(dataset, train_ratio=0.8):
    shuffled = dataset.copy()
    random.seed(42)
    random.shuffle(shuffled)
    split_idx = int(len(shuffled) * train_ratio)
    return shuffled[:split_idx], shuffled[split_idx:]


# Jsonl writing

def write_jsonl(data, filepath):
    with open(filepath, "w", encoding="utf-8") as f:
        for item in data:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")
    print(f"Saved {len(data)} examples -> {filepath}")


